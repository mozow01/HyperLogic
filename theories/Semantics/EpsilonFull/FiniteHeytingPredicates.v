Definition FHPredicate (X : b_ty) : Type := fh_base_denote X -> fh_carrier.

Definition FHPredicateLe {X : b_ty} (P Q : FHPredicate X) : Prop :=
  forall x, fh_le (P x) (Q x).

Global Instance FHPredicateCategory (X : b_ty) : SetoidCategory.
Proof.
  refine {|
    obj := FHPredicate X;
    hom := fun P Q => FHPredicateLe P Q;
    id := fun P x => fh_le_refl (P x);
    compose := fun P Q R g f x => fh_le_trans _ _ _ (f x) (g x);
    hom_equiv := fun _ _ _ _ => True
  |}.
  - intros. constructor; firstorder.
  - intros. exact I.
  - intros. exact I.
  - intros. exact I.
  - intros. exact I.
Defined.

Definition FHPredicateValue {X : b_ty}
  (P : @obj (FHPredicateCategory X)) (x : fh_base_denote X) : fh_carrier.
Proof.
  change (FHPredicate X) in P.
  exact (P x).
Defined.

Global Instance FHPredicateThin (X : b_ty) : Thin (FHPredicateCategory X).
Proof. intros P Q f g. exact I. Defined.

Global Instance FHPredicateCartesian (X : b_ty) :
  CartesianCategory (FHPredicateCategory X).
Proof.
  refine (@Build_Thin_CC (FHPredicateCategory X) (FHPredicateThin X)
    (fun _ => fh_top)
    (fun P x => fh_le_top (P x))
    (fun P Q x => fh_meet (P x) (Q x))
    (fun P Q R f g x => fh_le_meet _ _ _ (f x) (g x))
    (fun P Q x => fh_meet_le_l (P x) (Q x))
    (fun P Q x => fh_meet_le_r (P x) (Q x))).
Defined.

Global Instance FHPredicateClosed (X : b_ty) :
  CartesianClosedCategory (FHPredicateCategory X).
Proof.
  refine (@Build_Thin_CCC (FHPredicateCategory X) (FHPredicateThin X)
    (FHPredicateCartesian X)
    (fun P Q x => fh_impl (Q x) (P x))
    _ _).
  - intros P Q x.
    apply fh_impl_elim. apply fh_le_refl.
  - intros P Q R g x.
    apply fh_impl_intro. exact (g x).
Defined.

Global Instance FHPredicateBiClosed (X : b_ty) :
  BiCartesianClosedCategory (FHPredicateClosed X).
Proof.
  refine (@Build_Thin_BiCCC (FHPredicateCategory X)
    (FHPredicateCartesian X) (FHPredicateClosed X) (FHPredicateThin X)
    (fun _ => fh_bot)
    (fun P x => fh_bot_le (P x))
    (fun P Q x => fh_join (P x) (Q x))
    (fun P Q x => fh_le_join_l (P x) (Q x))
    (fun P Q x => fh_le_join_r (P x) (Q x))
    (fun P Q R f g x => fh_join_le _ _ _ (f x) (g x))).
Defined.

Lemma FHPredicateProduct_value (X : b_ty) (P Q : FHPredicate X) x :
  FHPredicateValue
    (@prod (FHPredicateCategory X) (FHPredicateCartesian X) P Q) x =
  fh_meet (P x) (Q x).
Proof. reflexivity. Defined.

Lemma FHPredicateCoproduct_value (X : b_ty) (P Q : FHPredicate X) x :
  FHPredicateValue
    (@coprod (FHPredicateCategory X) (FHPredicateCartesian X)
      (FHPredicateClosed X) (FHPredicateBiClosed X) P Q) x =
  fh_join (P x) (Q x).
Proof. reflexivity. Defined.

Lemma FHPredicateExponential_value (X : b_ty) (P Q : FHPredicate X) x :
  FHPredicateValue
    (@exp (FHPredicateCategory X) (FHPredicateCartesian X)
      (FHPredicateClosed X) P Q) x =
  fh_impl (Q x) (P x).
Proof. reflexivity. Defined.

Definition FHPullback {X Y : b_ty} (f : FHBaseHom X Y) :
  Functor (FHPredicateCategory Y) (FHPredicateCategory X).
Proof.
  refine (mk_Functor (FHPredicateCategory Y) (FHPredicateCategory X)
    (fun (P : FHPredicate Y) (x : fh_base_denote X) => P (f x))
    (fun (P Q : FHPredicate Y) (h : FHPredicateLe P Q)
      (x : fh_base_denote X) => h (f x)) _ _ _).
  - repeat red. intros. exact I.
  - intros. exact I.
  - intros. exact I.
Defined.

Fixpoint FHFiniteJoin (A : b_ty)
  (P : fh_base_denote A -> fh_carrier) : fh_carrier :=
  match A return (fh_base_denote A -> fh_carrier) -> fh_carrier with
  | b_Unit => fun Q => Q tt
  | b_S => fun Q => fh_join (Q true) (Q false)
  | b_Prod B C =>
      fun Q => FHFiniteJoin B (fun b => FHFiniteJoin C (fun c => Q (b, c)))
  end P.

Fixpoint FHFiniteMeet (A : b_ty)
  (P : fh_base_denote A -> fh_carrier) : fh_carrier :=
  match A return (fh_base_denote A -> fh_carrier) -> fh_carrier with
  | b_Unit => fun Q => Q tt
  | b_S => fun Q => fh_meet (Q true) (Q false)
  | b_Prod B C =>
      fun Q => FHFiniteMeet B (fun b => FHFiniteMeet C (fun c => Q (b, c)))
  end P.

Lemma FHFiniteJoin_upper : forall (A : b_ty)
  (P : fh_base_denote A -> fh_carrier) a,
  fh_le (P a) (FHFiniteJoin A P).
Proof.
  induction A; intros P a; cbn.
  - destruct a. apply fh_le_refl.
  - destruct a.
    + apply fh_le_join_l.
    + apply fh_le_join_r.
  - destruct a as [b c].
    eapply fh_le_trans.
    + exact (IHA2 (fun c' => P (b, c')) c).
    + exact (IHA1 (fun b' => FHFiniteJoin A2 (fun c' => P (b', c'))) b).
Defined.

Lemma FHFiniteJoin_least : forall (A : b_ty)
  (P : fh_base_denote A -> fh_carrier) z,
  (forall a, fh_le (P a) z) -> fh_le (FHFiniteJoin A P) z.
Proof.
  induction A; intros P z Hz; cbn.
  - apply Hz.
  - apply fh_join_le; apply Hz.
  - apply IHA1. intro b. apply IHA2. intro c. apply Hz.
Defined.

Lemma FHFiniteMeet_lower : forall (A : b_ty)
  (P : fh_base_denote A -> fh_carrier) a,
  fh_le (FHFiniteMeet A P) (P a).
Proof.
  induction A; intros P a; cbn.
  - destruct a. apply fh_le_refl.
  - destruct a.
    + apply fh_meet_le_l.
    + apply fh_meet_le_r.
  - destruct a as [b c].
    eapply fh_le_trans.
    + exact (IHA1 (fun b' => FHFiniteMeet A2 (fun c' => P (b', c'))) b).
    + exact (IHA2 (fun c' => P (b, c')) c).
Defined.

Lemma FHFiniteMeet_greatest : forall (A : b_ty)
  (P : fh_base_denote A -> fh_carrier) z,
  (forall a, fh_le z (P a)) -> fh_le z (FHFiniteMeet A P).
Proof.
  induction A; intros P z Hz; cbn.
  - apply Hz.
  - apply fh_le_meet; apply Hz.
  - apply IHA1. intro b. apply IHA2. intro c. apply Hz.
Defined.

Definition FHSigma {X A : b_ty} (Q : FHPredicate (b_Prod X A)) :
  FHPredicate X := fun x => FHFiniteJoin A (fun a => Q (x, a)).

Definition FHPi {X A : b_ty} (Q : FHPredicate (b_Prod X A)) :
  FHPredicate X := fun x => FHFiniteMeet A (fun a => Q (x, a)).

Definition FHSigmaUnit {X A : b_ty} (Q : FHPredicate (b_Prod X A)) :
  FHPredicateLe Q
    (fun xa : fh_base_denote (b_Prod X A) => FHSigma Q (Datatypes.fst xa)).
Proof.
  intros [x a].
  exact (FHFiniteJoin_upper A (fun a' => Q (x, a')) a).
Defined.

Definition FHPiCounit {X A : b_ty} (Q : FHPredicate (b_Prod X A)) :
  FHPredicateLe
    (fun xa : fh_base_denote (b_Prod X A) => FHPi Q (Datatypes.fst xa)) Q.
Proof.
  intros [x a].
  exact (FHFiniteMeet_lower A (fun a' => Q (x, a')) a).
Defined.

Definition FHProjectionPullbackRightAdjoint (X A : b_ty) :
  IsRightAdjoint (FHPullback (fun xa : fh_base_denote (b_Prod X A) => fst xa)).
Proof.
  refine (mk_IsRightAdjoint _ _
    (FHPullback (fun xa : fh_base_denote (b_Prod X A) => fst xa))
    (fun Q : FHPredicate (b_Prod X A) => FHSigma Q)
    (@FHSigmaUnit X A)
    (fun (Q : FHPredicate (b_Prod X A)) (P : FHPredicate X) h x =>
      FHFiniteJoin_least A (fun a => Q (x, a)) (P x) (fun a => h (x, a)))
    _ _ _).
  - repeat red. intros. exact I.
  - intros. exact I.
  - intros. exact I.
Defined.

Definition FHProjectionPullbackLeftAdjoint (X A : b_ty) :
  IsLeftAdjoint (FHPullback (fun xa : fh_base_denote (b_Prod X A) => fst xa)).
Proof.
  refine (mk_IsLeftAdjoint _ _
    (FHPullback (fun xa : fh_base_denote (b_Prod X A) => fst xa))
    (fun Q : FHPredicate (b_Prod X A) => FHPi Q)
    (@FHPiCounit X A)
    (fun (P : FHPredicate X) (Q : FHPredicate (b_Prod X A)) h x =>
      FHFiniteMeet_greatest A (fun a => Q (x, a)) (P x) (fun a => h (x, a)))
    _ _ _).
  - repeat red. intros. exact I.
  - intros. exact I.
  - intros. exact I.
Defined.

Definition FHPredicateIsoOfPointwiseEq {X : b_ty} (P Q : FHPredicate X)
  (H : forall x, P x = Q x) : @Iso (FHPredicateCategory X) P Q.
Proof.
  unshelve econstructor.
  - cbn. intro x. rewrite H. apply fh_le_refl.
  - cbn. intro x. rewrite H. apply fh_le_refl.
  - exact I.
  - exact I.
Defined.

Global Instance FHGoodFibration : GoodFibration FHBaseCategory.
Proof.
  refine {|
    Fiber := FHPredicateCategory;
    fiber_is_thin := FHPredicateThin;
    Fiber_is_Cartesian := FHPredicateCartesian;
    Fiber_is_Closed := FHPredicateClosed;
    Fiber_is_BiClosed := FHPredicateBiClosed;
    Pullback := fun X Y f => FHPullback f;
    pullback_has_left_adjoint := FHProjectionPullbackRightAdjoint;
    pullback_has_right_adjoint := FHProjectionPullbackLeftAdjoint
  |}.
  - intros X P. apply FHPredicateIsoOfPointwiseEq. reflexivity.
  - intros X Y Z g f P. apply FHPredicateIsoOfPointwiseEq. reflexivity.
  - intros X Y f. apply FHPredicateIsoOfPointwiseEq. reflexivity.
  - intros X Y f P Q. apply FHPredicateIsoOfPointwiseEq. reflexivity.
  - intros X Y f. apply FHPredicateIsoOfPointwiseEq. reflexivity.
  - intros X Y f P Q. apply FHPredicateIsoOfPointwiseEq. reflexivity.
  - intros X Y f P Q. apply FHPredicateIsoOfPointwiseEq. reflexivity.
  - intros X Y K f A0. apply FHPredicateIsoOfPointwiseEq. reflexivity.
  - intros X Y K f A0. apply FHPredicateIsoOfPointwiseEq. reflexivity.
  - intros X Y f g Hfg P. apply FHPredicateIsoOfPointwiseEq.
    intro x. cbn. apply f_equal. apply Hfg.
Defined.

(** The selector is executable and does not inspect a proof in Prop. *)
Fixpoint FHArgmax (A : b_ty)
  (P : fh_base_denote A -> fh_carrier) : fh_base_denote A :=
  match A return (fh_base_denote A -> fh_carrier) -> fh_base_denote A with
  | b_Unit => fun _ => tt
  | b_S => fun Q => if fh_le_dec (Q true) (Q false) then false else true
  | b_Prod B C => fun Q =>
      let b := FHArgmax B (fun x => FHFiniteJoin C (fun y => Q (x, y))) in
      (b, FHArgmax C (fun y => Q (b, y)))
  end P.

Lemma FHArgmax_spec : FiniteHeytingChain ->
  forall (A : b_ty) (P : fh_base_denote A -> fh_carrier),
  P (FHArgmax A P) = FHFiniteJoin A P.
Proof.
  intros Hchain A. induction A; intro P; cbn.
  - reflexivity.
  - destruct (fh_le_dec (P true) (P false)) as [Htf | Hntf].
    + apply fh_le_antisym.
      * apply fh_le_join_r.
      * apply fh_join_le; [exact Htf | apply fh_le_refl].
    + destruct (Hchain (P true) (P false)) as [Htf | Hft].
      * contradiction.
      * apply fh_le_antisym.
        -- apply fh_le_join_l.
        -- apply fh_join_le; [apply fh_le_refl | exact Hft].
  - set (b := FHArgmax A1
      (fun x => FHFiniteJoin A2 (fun y => P (x, y)))).
    transitivity (FHFiniteJoin A2 (fun y => P (b, y))).
    + exact (IHA2 (fun y => P (b, y))).
    + unfold b.
      exact (IHA1
        (fun x => FHFiniteJoin A2 (fun y => P (x, y)))).
Defined.

Definition FHPointwiseMaximum (X A : b_ty)
  (Q : FHPredicate (b_Prod X A)) (e : FHBaseHom X A) : Prop :=
  forall x, Q (x, e x) = FHFiniteJoin A (fun a => Q (x, a)).

Record FHMaximumSelectionData : Type := {
  fh_maximum_selector : forall (X A : b_ty),
    FHPredicate (b_Prod X A) -> FHBaseHom X A;
  fh_maximum_selector_spec : forall (X A : b_ty)
    (Q : FHPredicate (b_Prod X A)),
    FHPointwiseMaximum X A Q (fh_maximum_selector X A Q)
}.

Definition FHMaximumSelectionProperty : Prop :=
  forall (X A : b_ty) (Q : FHPredicate (b_Prod X A)),
    exists e : FHBaseHom X A, FHPointwiseMaximum X A Q e.

Definition FHChainMaximumSelectionData
  (Hchain : FiniteHeytingChain) : FHMaximumSelectionData.
Proof.
  refine {|
    fh_maximum_selector := fun X A Q x =>
      FHArgmax A (fun a => Q (x, a))
  |}.
  intros X A Q x.
  exact (FHArgmax_spec Hchain A (fun a => Q (x, a))).
Defined.

Lemma FHMaximumSelectionData_property :
  FHMaximumSelectionData -> FHMaximumSelectionProperty.
Proof.
  intros D X A Q. exists (fh_maximum_selector D X A Q).
  apply (fh_maximum_selector_spec D).
Defined.

Lemma FHMaximumSelectionProperty_chain :
  FHMaximumSelectionProperty -> FiniteHeytingChain.
Proof.
  intros Hsel u v.
  pose (Q := fun xb : fh_base_denote (b_Prod b_Unit b_S) =>
    if snd xb then u else v).
  destruct (Hsel b_Unit b_S Q) as [e He].
  specialize (He tt). cbn in He.
  destruct (e tt) eqn:Hev.
  - right.
    apply (fh_le_trans v (fh_join u v) u).
    + apply fh_le_join_r.
    + rewrite <- He. apply fh_le_refl.
  - left.
    apply (fh_le_trans u (fh_join u v) v).
    + apply fh_le_join_l.
    + rewrite <- He. apply fh_le_refl.
Defined.

Theorem FHMaximumSelection_iff_chain :
  FHMaximumSelectionProperty <-> FiniteHeytingChain.
Proof.
  split.
  - apply FHMaximumSelectionProperty_chain.
  - intro Hchain. apply FHMaximumSelectionData_property.
    exact (FHChainMaximumSelectionData Hchain).
Defined.

Theorem FHMaximumSelectionData_iff_chain :
  inhabited FHMaximumSelectionData <-> FiniteHeytingChain.
Proof.
  split.
  - intros [D]. apply FHMaximumSelectionProperty_chain.
    apply FHMaximumSelectionData_property. exact D.
  - intro Hchain. constructor. exact (FHChainMaximumSelectionData Hchain).
Defined.

Lemma FHPointwiseMaximum_to_EpsilonSelection :
  forall (X A : b_ty) (Q : FHPredicate (b_Prod X A)) (e : FHBaseHom X A),
  FHPointwiseMaximum X A Q e ->
  @EpsilonSelection FHBaseCategory FHBaseCartesian FHGoodFibration X A Q e.
Proof.
  intros X A Q e Hmax.
  apply FHPredicateIsoOfPointwiseEq. intro x. symmetry. apply Hmax.
Defined.

Lemma FHEpsilonSelection_to_PointwiseMaximum :
  forall (X A : b_ty) (Q : FHPredicate (b_Prod X A)) (e : FHBaseHom X A),
  @EpsilonSelection FHBaseCategory FHBaseCartesian FHGoodFibration X A Q e ->
  FHPointwiseMaximum X A Q e.
Proof.
  intros X A Q e Hsel x.
  destruct Hsel as [Hto Hfrom _ _]. cbn in Hto, Hfrom.
  apply fh_le_antisym.
  - exact (FHFiniteJoin_upper A (fun a => Q (x, a)) (e x)).
  - exact (Hto x).
Defined.

Theorem FHPointwiseMaximum_iff_EpsilonSelection :
  forall (X A : b_ty) (Q : FHPredicate (b_Prod X A)) (e : FHBaseHom X A),
  FHPointwiseMaximum X A Q e <->
  inhabited (@EpsilonSelection FHBaseCategory FHBaseCartesian
    FHGoodFibration X A Q e).
Proof.
  intros X A Q e. split.
  - intro H. constructor. apply FHPointwiseMaximum_to_EpsilonSelection. exact H.
  - intros [H]. apply FHEpsilonSelection_to_PointwiseMaximum. exact H.
Defined.

Definition FHAllPredicateEpsilonSelection : Prop :=
  forall (X A : b_ty) (Q : FHPredicate (b_Prod X A)),
  @EpsilonSelectionExists FHBaseCategory FHBaseCartesian
    FHGoodFibration X A Q.

Theorem FHAllPredicateEpsilonSelection_iff_maximum :
  FHAllPredicateEpsilonSelection <-> FHMaximumSelectionProperty.
Proof.
  split.
  - intros Hall X A Q.
    destruct (Hall X A Q) as [e He].
    exists e. apply FHEpsilonSelection_to_PointwiseMaximum. exact He.
  - intros Hall X A Q.
    destruct (Hall X A Q) as [e He].
    constructor 1 with e.
    apply FHPointwiseMaximum_to_EpsilonSelection. exact He.
Defined.

Theorem FHAllPredicateEpsilonSelection_iff_chain :
  FHAllPredicateEpsilonSelection <-> FiniteHeytingChain.
Proof.
  rewrite FHAllPredicateEpsilonSelection_iff_maximum.
  apply FHMaximumSelection_iff_chain.
Defined.

