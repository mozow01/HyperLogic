(** A finite Heyting algebra is presented by executable operations, a complete
    enumeration, and the order-theoretic laws used by the predicate fibers. *)
Class FiniteHeytingAlgebra := {
  fh_carrier : Type;
  fh_eq_dec : forall x y : fh_carrier, {x = y} + {x <> y};

  fh_le : fh_carrier -> fh_carrier -> Prop;
  fh_le_dec : forall x y, {fh_le x y} + {~ fh_le x y};
  fh_le_refl : forall x, fh_le x x;
  fh_le_trans : forall x y z, fh_le x y -> fh_le y z -> fh_le x z;
  fh_le_antisym : forall x y, fh_le x y -> fh_le y x -> x = y;

  fh_bot : fh_carrier;
  fh_top : fh_carrier;
  fh_meet : fh_carrier -> fh_carrier -> fh_carrier;
  fh_join : fh_carrier -> fh_carrier -> fh_carrier;
  fh_impl : fh_carrier -> fh_carrier -> fh_carrier;

  fh_bot_le : forall x, fh_le fh_bot x;
  fh_le_top : forall x, fh_le x fh_top;
  fh_meet_le_l : forall x y, fh_le (fh_meet x y) x;
  fh_meet_le_r : forall x y, fh_le (fh_meet x y) y;
  fh_le_meet : forall x y z, fh_le x y -> fh_le x z -> fh_le x (fh_meet y z);
  fh_le_join_l : forall x y, fh_le x (fh_join x y);
  fh_le_join_r : forall x y, fh_le y (fh_join x y);
  fh_join_le : forall x y z, fh_le x z -> fh_le y z -> fh_le (fh_join x y) z;
  fh_impl_intro : forall x y z, fh_le (fh_meet x y) z -> fh_le x (fh_impl y z);
  fh_impl_elim : forall x y z, fh_le x (fh_impl y z) -> fh_le (fh_meet x y) z;

  fh_enum : list fh_carrier;
  fh_enum_nodup : NoDup fh_enum;
  fh_enum_complete : forall x, In x fh_enum
}.

Arguments fh_carrier {_}.

Definition FiniteHeytingChain `{FiniteHeytingAlgebra} : Prop :=
  forall u v : fh_carrier, fh_le u v \/ fh_le v u.

(** The finite, inhabited base generated by 1, Bool, and products. *)
Fixpoint fh_base_denote (A : b_ty) : Type :=
  match A with
  | b_Unit => Datatypes.unit
  | b_S => Datatypes.bool
  | b_Prod B C => (fh_base_denote B * fh_base_denote C)%type
  end.

Fixpoint fh_base_default (A : b_ty) : fh_base_denote A :=
  match A with
  | b_Unit => tt
  | b_S => false
  | b_Prod B C => (fh_base_default B, fh_base_default C)
  end.

Fixpoint fh_base_enum (A : b_ty) : list (fh_base_denote A) :=
  match A with
  | b_Unit => [tt]
  | b_S => [true; false]
  | b_Prod B C =>
      flat_map (fun b => map (fun c => (b, c)) (fh_base_enum C))
        (fh_base_enum B)
  end.

Lemma fh_base_enum_complete :
  forall (A : b_ty) (x : fh_base_denote A), In x (fh_base_enum A).
Proof.
  induction A; intros x; cbn.
  - destruct x. auto.
  - destruct x; auto.
  - destruct x as [x y].
    apply in_flat_map. exists x. split.
    + apply IHA1.
    + apply in_map. apply IHA2.
Defined.

Definition FHBaseHom (A B : b_ty) : Type :=
  fh_base_denote A -> fh_base_denote B.

Definition FHBaseHomEquiv {A B : b_ty} (f g : FHBaseHom A B) : Prop :=
  forall x, f x = g x.

Global Instance FHBaseCategory : SetoidCategory.
Proof.
  refine {|
    obj := b_ty;
    hom := FHBaseHom;
    id := fun _ x => x;
    compose := fun _ _ _ g f x => g (f x);
    hom_equiv := @FHBaseHomEquiv
  |}.
  - intros A B. constructor.
    + intros f x. reflexivity.
    + intros f g Hfg x. symmetry. apply Hfg.
    + intros f g h Hfg Hgh x. rewrite (Hfg x), (Hgh x). reflexivity.
  - intros. intro a. reflexivity.
  - intros. intro a. reflexivity.
  - intros. intro a. reflexivity.
  - intros A B C f g h i Hfg Hhi x. rewrite (Hfg (h x)), (Hhi x). reflexivity.
Defined.

Global Instance FHBaseCartesian : CartesianCategory FHBaseCategory.
Proof.
  refine {|
    terminal := b_Unit;
    terminal_map := fun _ _ => tt;
    prod := b_Prod;
    prod_map := fun _ _ _ f g x => (f x, g x);
    prod_fst := fun _ _ xy => fst xy;
    prod_snd := fun _ _ xy => snd xy
  |}.
  - intros A f x. destruct (f x). reflexivity.
  - intros. intro a. reflexivity.
  - intros. intro a. reflexivity.
  - intros A B C h x.
    change ((Datatypes.pair (Datatypes.fst (h x)) (Datatypes.snd (h x))) = h x).
    destruct (h x). reflexivity.
  - intros A B C. red. intros f f' Hf g g' Hg x.
    rewrite (Hf x), (Hg x). reflexivity.
Defined.

Global Instance FHBaseTwoSort : TwoSortCategory FHBaseCategory.
Proof.
  refine {| S := b_S |}.
  discriminate.
Defined.

